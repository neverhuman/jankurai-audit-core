#[test]
fn changed_fast_inventories_unchanged_generic_supporting_evidence() {
    let dir = tempdir().unwrap();
    write_generic_support_fixture(dir.path());

    let report = run_changed_fast(dir.path(), "ops/ci/split-host-ci-parent.sh");

    assert_eq!(report.scope.mode, "changed-fast");
    assert_eq!(
        report.scope.paths,
        vec!["ops/ci/split-host-ci-parent.sh".to_string()]
    );
    for name in [
        "Contract and boundary integrity",
        "Security and supply-chain posture",
        "Data truth and workflow safety",
        "Observability and repair evidence",
    ] {
        assert!(
            dimension(&report, name).score >= 85,
            "{name} should retain real unchanged supporting evidence: {:?}",
            dimension(&report, name)
        );
    }
    assert_unrelated_source_excluded(&report);
}

#[test]
fn changed_fast_generic_roots_are_independently_required() {
    for (root, owning_dimension) in [
        ("contracts", "Contract and boundary integrity"),
        ("schemas", "Observability and repair evidence"),
        ("db", "Data truth and workflow safety"),
        (
            "tools/security-lane.sh",
            "Security and supply-chain posture",
        ),
    ] {
        let dir = tempdir().unwrap();
        write_generic_support_fixture(dir.path());
        let baseline = run_changed_fast(dir.path(), "ops/ci/split-host-ci-parent.sh");
        let baseline_score = dimension(&baseline, owning_dimension).score;

        match root {
            "contracts" | "schemas" | "db" => {
                fs::remove_dir_all(dir.path().join(root)).unwrap();
            }
            "tools/security-lane.sh" => {
                fs::write(
                    dir.path().join(root),
                    "#!/bin/sh\nset -eu\n# intentionally missing security commands\n",
                )
                .unwrap();
            }
            _ => unreachable!(),
        }

        let degraded = run_changed_fast(dir.path(), "ops/ci/split-host-ci-parent.sh");
        let degraded_score = dimension(&degraded, owning_dimension).score;
        assert!(
            degraded_score < baseline_score,
            "removing or corrupting {root} must lower {owning_dimension}: baseline={baseline_score}, degraded={degraded_score}"
        );
        assert_unrelated_source_excluded(&degraded);
    }
}

fn git(repo: &Path, args: &[&str]) {
    let status = Command::new("git")
        .arg("-C")
        .arg(repo)
        .args(args)
        .env("GIT_AUTHOR_NAME", "smoke")
        .env("GIT_AUTHOR_EMAIL", "smoke@example.com")
        .env("GIT_COMMITTER_NAME", "smoke")
        .env("GIT_COMMITTER_EMAIL", "smoke@example.com")
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_CONFIG_SYSTEM", "/dev/null")
        .env("JERYU_GIT_BYPASS", "1")
        .status()
        .expect("git invocation");
    assert!(status.success(), "git {args:?} failed");
}

/// The jeryu-deploy shape: release process documented in docs/release.md and
/// a README, neither touched by the diff. diff-audit must not report the
/// release-readiness hard finding or the agent-docs cap that the full audit
/// does not report.
#[test]
fn diff_audit_keeps_unchanged_release_doc_and_readme_in_scope() {
    let dir = tempdir().unwrap();
    let repo = dir.path();
    git(repo, &["init", "-q", "-b", "main"]);
    fs::write(repo.join("AGENTS.md"), "Read agent standard\n").unwrap();
    fs::write(
        repo.join("README.md"),
        "# Repo\n\n[![CI](https://img.shields.io/badge/ci-green.svg)](ci)\n\nBuilt on a Rust core. See [AGENTS.md](AGENTS.md).\n\n## Quick start\n\n```sh\ncargo test\n```\n",
    )
    .unwrap();
    fs::write(
        repo.join("Cargo.toml"),
        "[package]\nname = \"fixture\"\nversion = \"1.0.0\"\n",
    )
    .unwrap();
    fs::write(repo.join("CHANGELOG.md"), "# Changelog\n").unwrap();
    fs::write(
        repo.join("Justfile"),
        "check:\n    cargo test\nrelease:\n    cargo test\n",
    )
    .unwrap();
    fs::create_dir_all(repo.join("docs")).unwrap();
    fs::write(
        repo.join("docs/architecture.md"),
        "# Architecture\n\nRust workspace boundaries.\n",
    )
    .unwrap();
    fs::write(
        repo.join("docs/testing.md"),
        "# Testing\n\nRun cargo test.\n",
    )
    .unwrap();
    fs::write(
        repo.join("docs/release.md"),
        "# Release process\n\nThe release gate requires security review, backup rehearsal, monitoring, rollback, and rate limit abuse controls. Verify SHA256 checksums, provenance, and the SBOM before publication.\n",
    )
    .unwrap();
    fs::create_dir_all(repo.join("src")).unwrap();
    fs::write(repo.join("src/lib.rs"), "pub fn one() -> u8 { 1 }\n").unwrap();
    git(repo, &["add", "-A"]);
    git(repo, &["commit", "-q", "-m", "base"]);
    git(repo, &["checkout", "-q", "-b", "feature"]);
    fs::write(
        repo.join("src/lib.rs"),
        "pub fn one() -> u8 { 1 }\npub fn two() -> u8 { 2 }\n",
    )
    .unwrap();
    git(repo, &["commit", "-qam", "change"]);

    let out_dir = repo.join("target/jankurai/diff");
    let json = out_dir.join("diff-score.json");
    let output = Command::new(env!("CARGO_BIN_EXE_jankurai"))
        .arg("diff-audit")
        .arg(repo)
        .arg("--base-ref")
        .arg("main")
        .arg("--skip-proof")
        .arg("--advisory-only")
        .arg("--out-dir")
        .arg(&out_dir)
        .arg("--json")
        .arg(&json)
        .env("JERYU_GIT_BYPASS", "1")
        .env_remove("JANKURAI_DIFF_BASE")
        .env_remove("GITHUB_BASE_REF")
        .env_remove("CI_MERGE_REQUEST_DIFF_BASE_SHA")
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "diff-audit failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let report: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(&json).unwrap()).unwrap();
    assert_eq!(report["scope"]["mode"], "changed-fast");
    let caps: Vec<&str> = report["caps_applied"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|cap| cap.as_str())
        .collect();
    assert!(
        !caps.contains(&"release-readiness-gap"),
        "unchanged docs/release.md must count as release evidence: {caps:?}"
    );
    assert!(
        !caps.contains(&"missing-agent-readable-docs"),
        "unchanged README/docs must count as agent docs: {caps:?}"
    );
    let release_hard = report["findings"]
        .as_array()
        .unwrap()
        .iter()
        .any(|f| f["rule_id"] == "HLT-025-RELEASE-READINESS-GAP" && f["hardness"] == "hard");
    assert!(!release_hard, "no HLT-025 hard finding expected");
}
