//! Changed-fast (and so `diff-audit`) must inventory the unchanged control
//! files that repo-level dimensions read: README, docs/release.md, contracts,
//! db, schemas, rendered-UX evidence and the security lane. Without them a
//! diff-only audit reports release-readiness and agent-docs caps that the full
//! audit of the same commit does not (1.7.4 regression; split.6 kept these).

use jankurai::audit::{run_audit_with_options, AuditOptions};
use jankurai::model::{DimensionResult, Report};
use std::fs;
use std::path::Path;
use std::process::Command;
use tempfile::tempdir;

fn run_changed_fast(repo: &Path, changed: &str) -> Report {
    run_audit_with_options(
        repo,
        &[repo.join(changed)],
        AuditOptions {
            self_audit: false,
            proof_receipts: None,
            changed_fast: true,
        },
    )
    .unwrap()
}

fn dimension<'a>(report: &'a Report, name: &str) -> &'a DimensionResult {
    report
        .dimensions
        .iter()
        .find(|dim| dim.name == name)
        .unwrap_or_else(|| panic!("missing dimension {name}"))
}

fn assert_unrelated_source_excluded(report: &Report) {
    assert!(!report
        .findings
        .iter()
        .any(|finding| finding.path == "src/unrelated.rs"));
}

